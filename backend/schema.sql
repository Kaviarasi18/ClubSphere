-- ============================================================
-- ClubSphere Database Schema (PostgreSQL)
-- ------------------------------------------------------------
-- 1. Create the database (run once, outside this file):
--      createdb -U postgres clubsphere
--    or:  psql -U postgres -c "CREATE DATABASE clubsphere;"
-- 2. Load this schema into it:
--      psql -U postgres -d clubsphere -f backend/schema.sql
-- ============================================================

-- Needed to generate bcrypt hashes for the seed accounts.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============================================================
-- CLUBS
-- ============================================================
CREATE TABLE IF NOT EXISTS clubs (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                   VARCHAR(255) NOT NULL,
  category               VARCHAR(50)  NOT NULL
                         CHECK (category IN ('Technical','Cultural','Literary','Entrepreneurship','Social Impact')),
  description            TEXT         NOT NULL,
  logo                   VARCHAR(512) DEFAULT NULL,
  faculty_coordinator    VARCHAR(255) NOT NULL,
  student_coordinator    VARCHAR(255) NOT NULL,
  email                  VARCHAR(255) NOT NULL UNIQUE,
  status                 VARCHAR(20)  NOT NULL DEFAULT 'Pending'
                         CHECK (status IN ('Pending','Verified','Rejected')),
  identification_details TEXT         NOT NULL,
  coordinator_name       VARCHAR(255) NOT NULL,
  coordinator_email      VARCHAR(255) NOT NULL,
  rejection_note         TEXT         DEFAULT NULL,
  created_at             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- USERS
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(255) NOT NULL,
  username    VARCHAR(100) NOT NULL UNIQUE,
  email       VARCHAR(255) NOT NULL UNIQUE,
  password    VARCHAR(255) NOT NULL,   -- bcrypt hash
  role        VARCHAR(20)  NOT NULL DEFAULT 'student'
              CHECK (role IN ('admin','coordinator','student')),
  club_id     INTEGER      DEFAULT NULL REFERENCES clubs(id) ON DELETE SET NULL,
  department  VARCHAR(255) DEFAULT NULL,  -- for students
  year        VARCHAR(50)  DEFAULT NULL,  -- for students
  roll_number VARCHAR(100) DEFAULT NULL,  -- for students
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- EVENTS
-- ============================================================
CREATE TABLE IF NOT EXISTS events (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id        INTEGER      NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
  title          VARCHAR(255) NOT NULL,
  category       VARCHAR(50)  NOT NULL
                 CHECK (category IN ('Technical','Cultural','Literary','Entrepreneurship','Social Impact','Sports')),
  description    TEXT         NOT NULL,
  banner         VARCHAR(512) DEFAULT NULL,
  venue          VARCHAR(255) NOT NULL,
  start_datetime TIMESTAMP    NOT NULL,
  end_datetime   TIMESTAMP    NOT NULL,
  status         VARCHAR(20)  NOT NULL DEFAULT 'published'
                 CHECK (status IN ('published','cancelled')),
  created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- STUDENT FOLLOWED CLUBS
-- ============================================================
CREATE TABLE IF NOT EXISTS student_followed_clubs (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  INTEGER   NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  club_id     INTEGER   NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
  followed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_follow UNIQUE (student_id, club_id)
);

-- ============================================================
-- ANNOUNCEMENTS (club posts shown on the student feed)
-- ============================================================
CREATE TABLE IF NOT EXISTS announcements (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id   INTEGER     NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
  message   TEXT        NOT NULL,
  type      VARCHAR(30) NOT NULL DEFAULT 'announcement'
            CHECK (type IN ('announcement','update','reminder','resource','volunteer')),
  posted_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- Trigger to keep clubs.updated_at current
-- ============================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_clubs_updated_at ON clubs;
CREATE TRIGGER trg_clubs_updated_at
  BEFORE UPDATE ON clubs
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

